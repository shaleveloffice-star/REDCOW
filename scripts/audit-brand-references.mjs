import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

// Read source/document text only; never read local credentials or generated bundles.
const args = ['-n', '-i', '--hidden', '--glob', '!.git/**', '--glob', '!node_modules/**',
  '--glob', '!.next/**', '--glob', '!.codex*/**', '--glob', '!.vercel/**', '--glob', '!.env*',
  '--glob', '!data/local/uploads/**', '--glob', '!docs/REBRAND-REFERENCES-AFTER.md',
  'NB[ _-]?BURGER|\\bNB\\b|redcow', '.'];
let output;
try { output = execFileSync('rg', args, { encoding: 'utf8' }); }
catch (error) { if (error.status !== 1) throw error; output = error.stdout || ''; }
const rows = output.trim().split(/\r?\n/).filter(Boolean).map(line => {
  const match = line.match(/^\.\\(.*?):(\d+):(.*)$/) || line.match(/^\.\/(.*?):(\d+):(.*)$/);
  if (!match) throw new Error(`Unparsed reference: ${line}`);
  const [, rawFile, number, source] = match;
  const file = rawFile.replaceAll('\\', '/');
  let reason;
  if (file.startsWith('docs/') || file === 'README.md') reason = 'Historical inventory, migration instructions or unchanged repository name; not rendered site content.';
  else if (file.startsWith('tests/') || /(?:audit-brand|smoke-brand)/.test(file)) reason = 'Regression fixture/search rule: intentionally exercises or detects the old brand/domain.';
  else if (file.endsWith('site-domain.ts')) reason = 'Exact legacy hostname allowlist required for permanent redirects and CMS URL migration.';
  else if (file.endsWith('brand-migration.ts')) reason = 'Legacy-name matcher required to project existing CMS text to SO WHAT without destructive database updates.';
  else if (/upload-blob/.test(file)) reason = 'Existing Vercel Blob resource identity; renaming could break uploads.';
  else if (/nb_burger_story/.test(source)) reason = 'Existing structured-output API schema identifier; integration contract retained.';
  else if (/@|example\.com|instagram\.com/.test(source)) reason = 'Existing external account, email/sender or authentication identity; no replacement account was supplied.';
  else if (/storage|cookie|STORAGE|LOCALE_COOKIE|a11y-boot/.test(source)) reason = 'Persistent browser preference/draft key or DOM identifier; keeps existing sessions and preferences compatible.';
  else if (/images\/|videos\/|\.png|\.webp|\.jpg|\.mp4|\.webm|brand-sources/.test(source)) reason = 'Existing asset filename/path retained to avoid broken images and old image URLs; artwork replacements listed separately.';
  else if (/id:|"id"|slug|item-nb|item-meal-nb|nb-classic|meal-nb|hamburger-nb/i.test(source)) reason = 'Stable content ID, public slug or historical alias; deliberately preserved for SEO and CMS/translation references.';
  else reason = 'REVIEW REQUIRED';
  return { file, number, source: source.trim(), reason };
});
const escape = value => value.replaceAll('|', '\\|').replaceAll('`', "'");
const header = '# Remaining legacy references\n\nGenerated by `node scripts/audit-brand-references.mjs`. Each text match is recorded below. Binary artwork is covered in REBRAND-MIGRATION.md. Excludes secrets, build/dependency/cache/upload directories and this generated report itself. `.env.example` was checked separately and has no old-brand match. No public old-origin canonical, sitemap or JSON-LD URL remains in the HTTP audit.\n\n';
fs.writeFileSync('docs/REBRAND-REFERENCES-AFTER.md', header +
  `Matches: ${rows.length}.\n\n| File:line | Remaining reference | Why retained |\n|---|---|---|\n` +
  rows.map(row => `| ${escape(row.file)}:${row.number} | ${escape(row.source)} | ${row.reason} |`).join('\n') + '\n');
const unresolved = rows.filter(row => row.reason === 'REVIEW REQUIRED');
console.log(JSON.stringify({ matches: rows.length, unresolved }, null, 2));
if (unresolved.length) process.exitCode = 1;
